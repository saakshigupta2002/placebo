import type { TrialRecord } from "../core/types.js";
import {
  ADVERSE_LABELS,
  designLine,
  fmtCI,
  fmtEffect,
  fmtP,
  fmtValue,
  interventionLine,
  notesSummary,
  passCounts,
} from "./format.js";

export function renderMarkdown(t: TrialRecord): string {
  const r = t.results;
  const out: string[] = [];
  out.push(`# Placebo trial ${t.id}: ${t.intervention.label}`, "");
  if (!r) return `${out.join("\n")}\nTrial did not finish.\n`;
  out.push(`**Verdict: ${r.verdict.label}.** ${r.verdict.headline}`, "");
  out.push(`Testing ${interventionLine(t)} on ${designLine(t)}.`, "");
  if (r.metrics.length) {
    out.push("| | control | treatment | effect (95% CI) | p |", "|---|---|---|---|---|");
    for (const m of r.metrics) {
      let c = fmtValue(m, m.control);
      let tr = fmtValue(m, m.treatment);
      if (m.key === "pass") {
        const a = passCounts(t.runs, "control");
        const b = passCounts(t.runs, "treatment");
        c = `${a.passed}/${a.total}`;
        tr = `${b.passed}/${b.total}`;
      }
      out.push(`| ${m.label} | ${c} | ${tr} | ${fmtEffect(m)} ${fmtCI(m)} | ${fmtP(m.pValue)} |`);
    }
    out.push("");
  }
  if (r.activation) {
    const share = r.activation.runs
      ? Math.round((r.activation.fired / r.activation.runs) * 100)
      : 0;
    out.push(
      r.activation.control
        ? `- **Skill fired:** new version in ${r.activation.fired} of ${r.activation.runs} runs (${share}%), old version in ${r.activation.control.fired} of ${r.activation.control.runs}.`
        : `- **Skill fired** in ${r.activation.fired} of ${r.activation.runs} treatment runs (${share}%).`,
    );
  }
  const kinds = Object.entries(r.adverse.events).filter(([, v]) => v.control + v.treatment > 0);
  out.push(
    kinds.length
      ? `- **Adverse events:** ${kinds.map(([k, v]) => `${ADVERSE_LABELS[k] ?? k} (control ${v.control}, treatment ${v.treatment})`).join("; ")}.`
      : "- **Adverse events:** none in either arm.",
  );
  const noted = notesSummary(r.adverse.notes);
  if (noted) out.push(`- **Also noted (information, not adverse):** ${noted}.`);
  out.push(
    `- **Isolation:** ${t.isolation.verified ? "verified" : "not verified"} (${t.isolation.mode} mode). ${t.isolation.notes.join(" ")}`,
  );
  if (t.design.stoppedEarly) out.push(`- **Stopped early:** ${t.design.stoppedEarly}.`);
  out.push("");
  out.push("<details><summary>How this was measured</summary>", "");
  out.push(
    "Each task is a real change from the repository's history. The agent runs it twice in identical sealed workspaces exported without git history: once as is (control) and once with the intervention (treatment). " +
      "Hidden tests from the original change grade both attempts. Effects are estimated per task and averaged across tasks; p-values come from an exact paired sign-flip permutation test across tasks. The 95% intervals come from inverting that same test, so they always agree. " +
      "Pass rate is a difference in percentage points; tokens, cost and time are geometric-mean ratios.",
  );
  out.push(
    "",
    `Seed ${t.design.seed}. Generated by placebo ${t.placeboVersion} on ${t.createdAt.slice(0, 10)}.`,
    "",
    "</details>",
    "",
  );
  return out.join("\n");
}
